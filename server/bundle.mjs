// Builds dist/kapa-premium-worker.js: the whole server in one file, to paste into
// Cloudflare's online editor (Workers & Pages → your Worker → Edit code). Run: node bundle.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const here = new URL('.', import.meta.url);
const strip = text => text.replace(/^export (const|function) /gm, '$1 ');
const strategy = strip(readFileSync(new URL('strategy.js', here), 'utf8'));
const classic = strip(readFileSync(new URL('classic.js', here), 'utf8').replace(/^import \{[^}]*\} from '\.\/strategy\.js';\n/m, ''));
if (/from '\.\/strategy\.js'/.test(classic)) throw new Error('import of strategy.js not removed from classic.js');
const worker = readFileSync(new URL('worker.js', here), 'utf8')
    .replace(/^import \{[^}]*\} from '\.\/classic\.js';\n/m, '')
    .replace(/^import \{[^}]*\} from '\.\/strategy\.js';\n/m, '')
    .replace(/^export \{ estRatio \};.*\n?/m, '');
if (/from '\.\/(strategy|classic)\.js'/.test(worker)) throw new Error('import of strategy.js or classic.js not removed');
mkdirSync(new URL('dist/', here), { recursive: true });
const out = `// Kapa Premium server, single file for Cloudflare's online editor. Generated by server/bundle.mjs; edit worker.js, strategy.js and classic.js instead.\n\n${strategy}\n\n${classic}\n\n${worker}`;
writeFileSync(new URL('dist/kapa-premium-worker.js', here), out);
console.log(`dist/kapa-premium-worker.js written (${out.length} bytes)`);

// Netlify Function, importing the one-file server from premium-server/
mkdirSync(new URL('dist/netlify/functions/', here), { recursive: true });
writeFileSync(new URL('dist/netlify/functions/kapa.mjs', here), readFileSync(new URL('netlify/kapa.mjs', here), 'utf8'));
console.log('dist/netlify/functions/kapa.mjs written');
